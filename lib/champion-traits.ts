// Champion traits derived from Riot's own game data, never from hand-written champion lists, so every champion (and
// every rework or new release) is covered by the same rules.
//
// Source: CommunityDragon's copy of the League client's champion files
//   https://raw.communitydragon.org/<patch|latest>/plugins/rcp-be-lol-game-data/global/default/v1/champions/<id>.json
// (the same data the client serves at /lol-game-data/assets/v1/champions/<id>.json):
//   roles                    "marksman", "mage", "assassin", "fighter", "tank", "support" (primary first)
//   tacticalInfo.damageType  kPhysical / kMagic / kMixed; attackType melee / ranged
//   playstyleInfo            Riot's 0–3 ratings: damage, durability, crowdControl, mobility, utility
//   passive + spells         ability text with Riot's markup (<status>Stuns</status>, <healing>, <shield>,
//                            <physicalDamage>…) and each spell's cast range per rank
// Ability text gives the rest: healing/sustain, hard crowd control kinds (suppression first), long-range poke (cast
// ranges), dashes/blinks, crit scaling and on-hit. The keyword lists below are game concepts ("heal", "stun"), never
// champion names. Data Dragon tags/info are the fallback for a champion CommunityDragon does not have yet.
//
// Loading never blocks a poll; lookups are synchronous. Per Data Dragon patch:
//   1. the disk cache <memory>/cache/champion-traits-<patch>.json (compact raw ability data, re-derived on load, so a
//      change to the rules below needs no re-download), else
//   2. fetched from CommunityDragon in the background: the champions of the current game first, then the rest, a few
//      at a time; failures back off 1 min → 2 → 4 … → 1 h;
//   3. lib/champion-traits-fallback.json (derived traits, generated by scripts/build-champion-traits.ts) until then;
//   4. Data Dragon tags/info for a champion none of those know (a release newer than every table).
