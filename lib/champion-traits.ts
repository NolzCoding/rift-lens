export function championTraitsStatus() {
  const live = state.live;
  const fallback = bundled();
  return live && live.byKey.size
    ? { patch: live.patch, origin: live.origin, champions: new Set(live.byKey.values()).size, fallbackPatch: fallback.patch }
    : { patch: fallback.patch, origin: fallback.origin, champions: fallback.count, fallbackPatch: fallback.patch };
}

type IndexLike = ChampionIndex | ChampionEntry | null | undefined;
const isEntry = (value: IndexLike): value is ChampionEntry => Boolean(value && !(value instanceof Map) && typeof (value as ChampionEntry).id === "string");

/**
 * Traits for a champion (display name or Data Dragon id): this patch's data (disk cache / CommunityDragon) > the
 * bundled table > Data Dragon tags (`index` or an entry) > unknown. Synchronous; never touches disk or network.
 */
export function championTraits(champion: string, index?: IndexLike): ChampionTraits {
  const wanted = championKey(champion);
  const entry = isEntry(index) ? index : index instanceof Map ? index.get(wanted) || null : null;
  const keys = [wanted, ...(entry ? [championKey(entry.id), championKey(entry.name)] : [])];
  for (const table of [state.live?.byKey, bundled().byKey]) {
    if (!table) continue;
    for (const name of keys) { const found = table.get(name); if (found) return found; }
  }
  return entry ? traitsFromDataDragon(entry) : unknownTraits(champion);
}

const cachePath = (patch: string) => path.join(memoryRoot(), "cache", `champion-traits-${patch.replace(/[^0-9a-z.]/gi, "_")}.json`);

/** Only what the derivation reads: skins, chromas and media paths are dropped (the full files are ~40 KB each). */
export function compactRaw(raw: RawChampionData): RawChampionData {
  return {
    id: raw.id, name: raw.name, alias: raw.alias, roles: raw.roles, tacticalInfo: raw.tacticalInfo, playstyleInfo: raw.playstyleInfo,
    passive: { name: raw.passive?.name, description: raw.passive?.description },
    spells: (raw.spells || []).map((spell) => ({ spellKey: spell.spellKey, name: spell.name, description: spell.description, dynamicDescription: spell.dynamicDescription, range: spell.range })),
  };
}

function deriveRaw(raw: RawCache["champions"][string]) {
  const entry = raw.ddId ? { id: raw.ddId, key: raw.ddKey || String(raw.id ?? ""), name: raw.ddName || raw.name || raw.ddId, tags: [], info: { attack: 0, defense: 0, magic: 0, difficulty: 0 } } : null;
  return deriveChampionTraits(raw, entry);
}

function setLive(patch: string, raw: RawCache["champions"], origin: Compiled["origin"]) {
  const live: Live = { patch, raw, origin, byKey: new Map() };
  for (const value of Object.values(raw)) {
    const traits = deriveRaw(value);
    for (const name of [traits.id, traits.name, value.alias || ""]) if (name) live.byKey.set(championKey(name), traits);
  }
  state.live = live;
}

function addLive(patch: string, id: string, raw: RawCache["champions"][string]) {
  if (!state.live || state.live.patch !== patch) state.live = { patch, raw: {}, origin: "communitydragon", byKey: new Map() };
  state.live.raw[id] = raw;
  state.live.origin = "communitydragon";
  const traits = deriveRaw(raw);
  for (const name of [traits.id, traits.name, raw.alias || ""]) if (name) state.live.byKey.set(championKey(name), traits);
}

/** Fetches one champion file: the patch's CommunityDragon folder first, `latest` when that patch is not published. */
async function fetchChampion(refresh: Refresh, numericKey: string): Promise<RawChampionData> {
  const [major, minor] = refresh.patch.split(".");
  const bases = refresh.base ? [refresh.base] : [...(major && minor ? [`${CDRAGON}/${major}.${minor}`] : []), `${CDRAGON}/latest`];
  let lastError: unknown = null;
  for (const base of bases) {
    try {
      // no-store: ~40 KB per file × 170 must not land in Next's fetch cache; only the compact subset is kept.
      const response = await fetch(`${base}/${CHAMPION_PATH}/champions/${numericKey}.json`, { cache: "no-store", signal: AbortSignal.timeout(FETCH_TIMEOUT_MS) });
      if (!response.ok) throw new Error(`CommunityDragon ${response.status} for champion ${numericKey}`);
      const raw = compactRaw(await response.json() as RawChampionData);
      refresh.base = base;
      return raw;
    } catch (error) { lastError = error; }
  }
  throw lastError instanceof Error ? lastError : new Error(`CommunityDragon champion ${numericKey} unavailable`);
}

type Wanted = { id: string; key: string; name: string };

/** Every champion of the index (unique entries), the given names first. */
function wantedChampions(index: ChampionIndex | null | undefined, priority: string[]): Wanted[] {
  const unique = new Map<string, Wanted>();
  for (const entry of index?.values() || []) if (entry.key && !unique.has(entry.id)) unique.set(entry.id, { id: entry.id, key: entry.key, name: entry.name });
  const first = new Set(priority.map(championKey));
  return [...unique.values()].sort((a, b) => Number(first.has(championKey(b.name)) || first.has(championKey(b.id))) - Number(first.has(championKey(a.name)) || first.has(championKey(a.id))));
}

/** Downloads every listed champion (CONCURRENCY at a time); calls `onChampion` as each lands. Throws when any failed. */
export async function fetchChampionData(patch: string, champions: Wanted[], onChampion: (champion: Wanted, raw: RawChampionData) => void = () => undefined) {
  const refresh: Refresh = { patch, disk: null, inFlight: true, failures: 0, retryAt: 0, done: false, base: null, wanted: new Set() };
  const queue = [...champions];
  const failed: string[] = [];
  const worker = async () => {
    for (let next = queue.shift(); next; next = queue.shift()) {
      try { onChampion(next, await fetchChampion(refresh, next.key)); } catch { failed.push(next.id); }
    }
  };
  await Promise.all(Array.from({ length: CONCURRENCY }, worker));
  if (failed.length) throw new Error(`CommunityDragon: ${failed.length} champion file(s) failed (${failed.slice(0, 5).join(", ")})`);
  return refresh.base;
}

function startNetwork(refresh: Refresh, index: ChampionIndex | null | undefined, priority: string[]) {
  if (!state.network || refresh.inFlight || refresh.done || Date.now() < refresh.retryAt) return;
  const have = state.live?.patch === refresh.patch ? state.live.raw : {};
  const missing = wantedChampions(index, priority).filter((champion) => !have[champion.id]);
  if (!missing.length) { refresh.done = Boolean(index?.size); return; }
  refresh.inFlight = true;
  void fetchChampionData(refresh.patch, missing, (champion, raw) => {
    if (state.refresh !== refresh) return;
    addLive(refresh.patch, champion.id, { ...raw, ddId: champion.id, ddKey: champion.key, ddName: champion.name });
  }).then(() => { if (state.refresh === refresh) refresh.done = true; }).catch((error) => {
    refresh.failures += 1;
    refresh.retryAt = Date.now() + Math.min(RETRY_MAX_MS, RETRY_MIN_MS * 2 ** (refresh.failures - 1));
    if (refresh.failures === 1) console.warn(`[champion-traits] ${error instanceof Error ? error.message : error}; using the bundled table for those, retrying with back-off.`);
  }).finally(async () => {
    refresh.inFlight = false;
    // Whatever landed is cached (a later start only fetches what is still missing).
    if (state.refresh === refresh && state.live?.patch === refresh.patch && state.disk) {
      const cache: RawCache = { patch: refresh.patch, source: `${refresh.base || CDRAGON} champions/<id>.json`, generatedAt: new Date().toISOString().slice(0, 10), champions: state.live.raw };
      await writeJsonAtomic(cachePath(refresh.patch), cache).catch((error) => console.warn(`[champion-traits] cache write failed: ${error instanceof Error ? error.message : error}`));
    }
  });
}

/**
 * Makes sure this patch's traits are loaded or loading; never blocks on the network (the returned promise settles once
 * the disk cache was checked). Call on every poll with the champions in the game: they are fetched first.
 */
export function ensureChampionTraits(patch: string, index: ChampionIndex | null | undefined, priority: string[] = []): Promise<void> {
  if (!patch) return Promise.resolve();
  let refresh = state.refresh;
  if (!refresh || refresh.patch !== patch) {
    const fresh: Refresh = { patch, disk: null, inFlight: false, failures: 0, retryAt: 0, done: false, base: null, wanted: new Set() };
    state.refresh = refresh = fresh;
    const read = state.disk ? readFile(cachePath(patch), "utf8").then((text) => JSON.parse(text) as RawCache) : Promise.reject(new Error("disk off"));
    fresh.disk = read.then((cache) => {
      if (state.refresh === fresh && cache.champions && Object.keys(cache.champions).length) setLive(patch, cache.champions, "cache");
    }).catch(() => undefined).then(() => { if (state.refresh === fresh) startNetwork(fresh, index, priority); });
    return fresh.disk;
  }
  if (!refresh.done && refresh.disk) void refresh.disk.then(() => startNetwork(refresh!, index, priority));
  return refresh.disk || Promise.resolve();
}

/** Builds a bundled-table payload from raw champion data (scripts/build-champion-traits.ts). */
export function traitsTable(patch: string, source: string, champions: Array<{ id: string; key: string; name: string; raw: RawChampionData }>): TraitsTable {
  const table: TraitsTable = { patch, source, generatedAt: new Date().toISOString().slice(0, 10), algorithm: TRAITS_ALGORITHM, champions: {} };
  for (const champion of [...champions].sort((a, b) => a.id.localeCompare(b.id))) {
    table.champions[champion.id] = deriveChampionTraits(champion.raw, { id: champion.id, key: champion.key, name: champion.name, tags: [], info: { attack: 0, defense: 0, magic: 0, difficulty: 0 } });
  }
  return table;
}
