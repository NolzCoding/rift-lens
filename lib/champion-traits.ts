/** Bump when the derivation rules change: the bundled table must then be regenerated (a test checks it). */
export const TRAITS_ALGORITHM = 2;

export type DamageType = "physical" | "magic" | "mixed" | "unknown";
export type CcKind = "suppress" | "stun" | "root" | "charm" | "taunt" | "fear" | "sleep" | "polymorph" | "knockup" | "knockback" | "pull";
export type Ratings = { damage: number; durability: number; crowdControl: number; mobility: number; utility: number };

export type ChampionTraits = {
  /** Data Dragon id ("MonkeyKing"), display name ("Wukong"), numeric key ("62"). */
  id: string;
  name: string;
  key: string;
  /** Riot's class roles, primary first (CommunityDragon), else Data Dragon tags lower-cased. */
  roles: string[];
  damage: DamageType;
  ranged: boolean;
  ratings: Ratings;
  /** Healing/sustain weight 0–2 (healScore = abilities that heal, +1 for a support healing allies). */
  healing: number;
  healScore: number;
  /** Cleansable lockdown weight 0–2: 2 = suppression, 1 = a crowd-control kit (see deriveChampionTraits). */
  hardCc: number;
  ccKinds: CcKind[];
  /** Abilities with stun / root / charm / taunt / fear / sleep / polymorph / suppression (what QSS removes). */
  cleansableCc: number;
  /** Long-range poke weight 0–2 from damaging basic-ability cast ranges (ranged champions). */
  poke: number;
  pokeScore: number;
  /** Longest cast range of a damaging basic ability. */
  pokeRange: number;
  /** Abilities with a dash / blink / leap. */
  dashes: number;
  /** The kit scales with critical strike (passive mentions it, or two abilities do). */
  critScaling: boolean;
  /** The kit applies on-hit effects / scales with attacks. */
  onHit: boolean;
  /** Heals or shields allies. */
  allyUtility: boolean;
  source: "communitydragon" | "datadragon" | "none";
};

/** The compact subset of a CommunityDragon champion file the derivation reads (what the disk cache stores). */
export type RawChampionData = {
  id?: number;
  name?: string;
  alias?: string;
  roles?: string[];
  tacticalInfo?: { damageType?: string; attackType?: string; style?: number };
  playstyleInfo?: Partial<Ratings>;
  passive?: { name?: string; description?: string };
  spells?: Array<{ spellKey?: string; name?: string; description?: string; dynamicDescription?: string; range?: number[] }>;
};

