// Class helpers (what the build engine and the enemy profile ask)

export const isTank = (traits: ChampionTraits) => traits.roles[0] === "tank";
/** Physical ranged carries: a marksman-primary champion, or a support whose second role is marksman. Magic ones (AP on-hit) are mages here. */
export const isMarksman = (traits: ChampionTraits) =>
  (traits.roles[0] === "marksman" || (traits.roles[0] === "support" && traits.roles[1] === "marksman")) && traits.damage !== "magic";
/**
 * Supports whose kit heals/shields allies and is not built around damage (Riot damage rating ≤ 2): support-primary, or a
 * mage/support that also heals. Tank supports are engage supports instead.
 */
export const isEnchanter = (traits: ChampionTraits) =>
  traits.roles.includes("support") && !traits.roles.includes("tank") && traits.allyUtility && !isMarksman(traits)
  && (traits.roles[0] === "support" || traits.healing >= 1) && (traits.ratings.damage || 1) <= 2;
/** Burst divers: assassin-role champions (not marksmen), and fighters with a dash and real mobility. */
export const isDiver = (traits: ChampionTraits) =>
  (traits.roles.includes("assassin") && traits.roles[0] !== "marksman") || (traits.roles[0] === "fighter" && traits.dashes >= 1 && traits.ratings.mobility >= 2);

export type BuildClass =
  | "marksman-crit" | "marksman-onhit" | "mage-burst" | "mage-battle" | "assassin-ad" | "assassin-ap"
  | "fighter" | "fighter-crit" | "tank" | "enchanter" | "engage-support" | "unknown";

/** The class whose default items fit the champion (used only when no researched/player build exists). */
export function buildClass(traits: ChampionTraits): BuildClass {
  const roles = traits.roles;
  if (!roles.length) return "unknown";
  const magic = traits.damage === "magic";
  if (isMarksman(traits)) return traits.critScaling || !traits.onHit ? "marksman-crit" : "marksman-onhit";
  if (roles.includes("support") && roles.includes("tank")) return "engage-support";
  if (isTank(traits)) return "tank";
  if (isEnchanter(traits)) return "enchanter";
  // A durable crowd-control support that is not a mage or an assassin (engage without the tank role).
  if (roles.includes("support") && traits.ratings.crowdControl >= 3 && traits.ratings.durability >= 2 && roles[0] !== "mage" && !roles.includes("assassin")) return "engage-support";
  if (roles[0] === "assassin" || (roles[0] === "support" && roles[1] === "assassin")) return magic ? "assassin-ap" : "assassin-ad";
  if (roles[0] === "mage" || magic) {
    const battle = !traits.ranged || traits.ratings.durability >= 2 || roles.includes("fighter") || roles.includes("tank") || roles[0] === "marksman";
    return battle ? "mage-battle" : "mage-burst";
  }
  if (roles[0] === "fighter" || roles.includes("fighter")) return traits.critScaling ? "fighter-crit" : "fighter";
  return traits.damage === "physical" ? "fighter" : "unknown";
}

