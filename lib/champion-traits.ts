/** Disk cache: the compact raw data (re-derived on load). */
type RawCache = { patch: string; source: string; generatedAt: string; champions: Record<string, RawChampionData & { ddId?: string; ddKey?: string; ddName?: string }> };

const FALLBACK_FILE = "champion-traits-fallback.json";
const CDRAGON = "https://raw.communitydragon.org";
const CHAMPION_PATH = "plugins/rcp-be-lol-game-data/global/default/v1";
const RETRY_MIN_MS = 60_000;
const RETRY_MAX_MS = 60 * 60_000;
const FETCH_TIMEOUT_MS = 15_000;
const CONCURRENCY = 4;

type Compiled = { patch: string; origin: "fallback" | "cache" | "communitydragon" | "test" | "empty"; byKey: Map<string, ChampionTraits>; count: number };

function compile(champions: Iterable<ChampionTraits>, patch: string, origin: Compiled["origin"]): Compiled {
  const byKey = new Map<string, ChampionTraits>();
  let count = 0;
  for (const traits of champions) {
    count += 1;
    for (const name of [traits.id, traits.name]) if (name) byKey.set(championKey(name), traits);
  }
  return { patch, origin, byKey, count };
}

let fallbackTable: Compiled | null = null;
function bundled(): Compiled {
  if (fallbackTable) return fallbackTable;
  try {
    const table = JSON.parse(readFileSync(path.join(process.cwd(), "lib", FALLBACK_FILE), "utf8")) as TraitsTable;
    fallbackTable = compile(Object.values(table.champions || {}), table.patch, "fallback");
  } catch {
    fallbackTable = compile([], "none", "empty");
  }
  return fallbackTable;
}
/** The bundled table as generated (tests check its algorithm version). */
export function bundledTraitsTable(): TraitsTable | null {
  try { return JSON.parse(readFileSync(path.join(process.cwd(), "lib", FALLBACK_FILE), "utf8")) as TraitsTable; } catch { return null; }
}

type Live = { patch: string; byKey: Map<string, ChampionTraits>; raw: RawCache["champions"]; origin: Compiled["origin"] };
