// Derivation (pure)

type Ability = { slot: "p" | "q" | "w" | "e" | "r"; text: string; range: number };

/** Grievous Wounds / "reduces healing" describe the opposite of sustain. */
const NOT_HEALING = /grievous wounds|\bwounds\b|reduc\w*(?: \w+){0,3} heal\w*|healing reduction|anti-?heal|heal and shield power/gi;
const HEALING = /<healing>|\bheal(?:s|ing|ed)?\b|restor\w*(?: \w+){0,4} health|health regen|omnivamp|life ?steal|physical vamp|\bdrains?\b/i;
const ALLY = /\b(?:all(?:y|ies|ied)|teammates?)\b/i;
const SHIELD = /<shield>|\bshield(?:s|ing|ed)?\b/i;
const DAMAGE = /<(?:magic|physical|true)Damage>|\b(?:magic|physical|true) damage\b/i;
const DASH = /\b(?:dash(?:es|ing)?|blinks?|leaps?|lunges?|vaults?|teleports?(?! to (?:a )?(?:turret|tower))|jumps? (?:to|toward|at)|charges? (?:forward|toward|at|in a direction)|surges? forward|flips? over)\b/i;
const CRIT = /critical strike|\bcrit(?:s|ically)?\b/i;
const ON_HIT = /on-hit|<OnHit>/i;
/** Riot marks crowd control as <status>Stuns</status>; the plain-text patterns cover Data Dragon text without markup. */
const CC_PATTERNS: Array<[CcKind, RegExp]> = [
  ["suppress", /suppress/], ["stun", /stun/], ["root", /root|immobiliz|snare/], ["charm", /charm/], ["taunt", /taunt|berserk/],
  ["fear", /fear|flee/], ["sleep", /sleep|asleep|drows/], ["polymorph", /polymorph/],
  ["knockup", /knock\w* up|airborne/], ["pull", /\bpull|\bdrag/], ["knockback", /knock|push/],
];
/** Crowd control a cleanse (QSS / Mercurial Scimitar) removes: Airborne effects (knock-ups, pulls) are not. */
const CLEANSABLE = new Set<CcKind>(["suppress", "stun", "root", "charm", "taunt", "fear", "sleep", "polymorph"]);
const PLAIN_CC = /\b(?:stun\w*|root\w*|suppress\w*|charm\w*|taunt\w*|fear\w*|sleep|asleep|polymorph\w*|knock\w* (?:up|back|away)|airborne|pull\w*)\b/gi;

const strip = (text = "") => text.replace(/<br\s*\/?>/gi, " ").replace(/\s+/g, " ");
const clamp = (value: number, low: number, high: number) => Math.min(high, Math.max(low, value));
const ratingOf = (value: unknown) => (typeof value === "number" && Number.isFinite(value) ? value : 0);

function ccKindsOf(text: string): CcKind[] {
  const marked = [...text.matchAll(/<status>([^<]*)<\/status>/gi)].map((match) => match[1].toLowerCase());
  const phrases = marked.length ? marked : [...text.matchAll(PLAIN_CC)].map((match) => match[0].toLowerCase());
  const kinds = new Set<CcKind>();
  for (const phrase of phrases) {
    const found = CC_PATTERNS.find(([, pattern]) => pattern.test(phrase));
    if (found) kinds.add(found[0]);
  }
  return [...kinds];
}

function damageTypeOf(raw: string | undefined): DamageType {
  const value = (raw || "").toLowerCase();
  if (value.includes("mixed")) return "mixed";
  if (value.includes("physical")) return "physical";
  if (value.includes("magic")) return "magic";
  return "unknown";
}

/**
 * Traits from one CommunityDragon champion file. Rules (thresholds are about game concepts, never champions):
 *  - healing: each ability whose text heals (<healing>, "restores health", omnivamp, life steal, drain) counts 1, 1.5 when
 *    it carries two or more <healing> amounts; a support that heals allies adds 1. Weight 2 at ≥ 3, 1 at ≥ 2.
 *  - hard CC: suppression = 2; otherwise 1 for two or more abilities with cleansable CC, or one when Riot rates the
 *    champion's crowd control 3/3.
 *  - poke (ranged champions): damaging Q/W/E add (range − 850) / 400 each (0–1), an artillery ultimate (3000–5000
 *    range) 0.5. Weight 2 at ≥ 1.5, 1 at ≥ 0.75.
 *  - crit scaling: the passive mentions critical strikes, or two abilities do.
 */
export function deriveChampionTraits(raw: RawChampionData, entry?: Pick<ChampionEntry, "id" | "key" | "name" | "tags" | "info"> | null): ChampionTraits {
  const roles = (raw.roles || []).map((role) => role.toLowerCase()).filter(Boolean);
  const ratings: Ratings = {
    damage: ratingOf(raw.playstyleInfo?.damage), durability: ratingOf(raw.playstyleInfo?.durability), crowdControl: ratingOf(raw.playstyleInfo?.crowdControl),
    mobility: ratingOf(raw.playstyleInfo?.mobility), utility: ratingOf(raw.playstyleInfo?.utility),
  };
  const abilities: Ability[] = [
    { slot: "p", text: strip(raw.passive?.description), range: 0 },
    ...(raw.spells || []).slice(0, 4).map((spell, at): Ability => ({
      slot: ((spell.spellKey || "qwer"[at] || "q").toLowerCase() as Ability["slot"]),
      text: strip(`${spell.description || ""} ${spell.dynamicDescription || ""}`),
      range: Math.max(0, ...(spell.range || []).filter((value) => Number.isFinite(value) && value <= 5000)),
    })),
  ];
  const ranged = (raw.tacticalInfo?.attackType || "").toLowerCase() === "ranged";
  const support = roles.includes("support");

  let healScore = 0;
  let allyHeal = false;
  let allyUtility = false;
  let cleansableCc = 0;
  let suppression = false;
  let pokeScore = 0;
  let pokeRange = 0;
  let dashes = 0;
  let critMentions = 0;
  let passiveCrit = false;
  let onHit = false;
  const kinds = new Set<CcKind>();
  for (const ability of abilities) {
    const text = ability.text;
    const sustainText = text.replace(NOT_HEALING, " ");
    const heals = HEALING.test(sustainText);
    if (heals) healScore += (sustainText.match(/<healing>/gi) || []).length >= 2 ? 1.5 : 1;
    if (ALLY.test(text) && heals) allyHeal = true;
    if (ALLY.test(text) && (heals || SHIELD.test(text))) allyUtility = true;
    const cc = ccKindsOf(text);
    cc.forEach((kind) => kinds.add(kind));
    if (cc.some((kind) => CLEANSABLE.has(kind))) cleansableCc += 1;
    if (cc.includes("suppress")) suppression = true;
    if (DAMAGE.test(text) && ability.slot !== "p") {
      if (ability.slot === "r") { if (ability.range >= 3000) pokeScore += 0.5; }
      else {
        pokeScore += clamp((ability.range - 850) / 400, 0, 1);
        pokeRange = Math.max(pokeRange, ability.range);
      }
    }
    if (DASH.test(text)) dashes += 1;
    if (CRIT.test(text)) { critMentions += 1; if (ability.slot === "p") passiveCrit = true; }
    if (ON_HIT.test(text)) onHit = true;
  }
  if (support && allyHeal) healScore += 1;
  if (!ranged) pokeScore *= 0.5;
  pokeScore = Math.round(pokeScore * 100) / 100;
  const hardCc = suppression ? 2 : cleansableCc >= 2 || (cleansableCc >= 1 && ratings.crowdControl >= 3) ? 1 : 0;
  const damage = damageTypeOf(raw.tacticalInfo?.damageType);
  return {
    id: entry?.id || raw.alias || raw.name || String(raw.id ?? ""),
    name: entry?.name || raw.name || raw.alias || "",
    key: entry?.key || String(raw.id ?? ""),
    roles: roles.length ? roles : (entry?.tags || []).map((tag) => tag.toLowerCase()),
    damage: damage !== "unknown" ? damage : entry ? inferDamageProfile(entry as ChampionEntry) : "unknown",
    ranged,
    ratings,
    healing: healScore >= 3 ? 2 : healScore >= 2 ? 1 : 0,
    healScore,
    hardCc,
    ccKinds: [...kinds],
    cleansableCc,
    poke: pokeScore >= 1.5 ? 2 : pokeScore >= 0.75 ? 1 : 0,
    pokeScore,
    pokeRange,
    dashes,
    critScaling: passiveCrit || critMentions >= 2,
    onHit,
    allyUtility,
    source: "communitydragon",
  };
}

/** Data Dragon tags/info only (a champion no CommunityDragon table knows yet): class and damage, no ability signals. */
export function traitsFromDataDragon(entry: Pick<ChampionEntry, "id" | "key" | "name" | "tags" | "info">): ChampionTraits {
  const roles = entry.tags.map((tag) => tag.toLowerCase());
  return {
    id: entry.id, name: entry.name, key: entry.key, roles, damage: inferDamageProfile(entry as ChampionEntry), ranged: roles[0] === "marksman" || roles[0] === "mage",
    ratings: { damage: 0, durability: 0, crowdControl: 0, mobility: 0, utility: 0 }, healing: 0, healScore: 0, hardCc: 0, ccKinds: [], cleansableCc: 0,
    poke: 0, pokeScore: 0, pokeRange: 0, dashes: 0, critScaling: roles[0] === "marksman", onHit: false, allyUtility: roles[0] === "support", source: "datadragon",
  };
}

function unknownTraits(champion: string): ChampionTraits {
  return {
    id: champion, name: champion, key: "", roles: [], damage: "unknown", ranged: false, ratings: { damage: 0, durability: 0, crowdControl: 0, mobility: 0, utility: 0 },
    healing: 0, healScore: 0, hardCc: 0, ccKinds: [], cleansableCc: 0, poke: 0, pokeScore: 0, pokeRange: 0, dashes: 0, critScaling: false, onHit: false, allyUtility: false, source: "none",
  };
}

