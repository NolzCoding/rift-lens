// Regenerates lib/item-tips-data.ts: the "how to use it" line per Summoner's Rift item, generated from the current Data
// Dragon item descriptions with the rules in lib/item-synergy.ts. It answers where the live catalog has not registered
// this patch's tips (client components, offline). Run from the project folder:
//   node --import ./scripts/alias.mjs --experimental-transform-types --no-warnings scripts/build-item-tips.ts [--print]
import { writeFile } from "node:fs/promises";
import path from "node:path";

import { itemUsageTip } from "@/lib/item-synergy";

type RawItem = { name?: string; description?: string; tags?: string[]; maps?: Record<string, boolean>; gold?: { purchasable?: boolean; total?: number }; requiredChampion?: string; requiredAlly?: string; inStore?: boolean };
const versions = await (await fetch("https://ddragon.leagueoflegends.com/api/versions.json")).json() as string[];
const version = versions[0];
const payload = await (await fetch(`https://ddragon.leagueoflegends.com/cdn/${version}/data/en_US/item.json`)).json() as { data: Record<string, RawItem> };
const key = (value = "") => value.toLowerCase().replace(/[^a-z0-9]/g, "");
const tips = new Map<string, { name: string; tip: string }>();
// Same filter as the live catalog (lib/live-game.ts fetchCatalog); the lowest id wins on duplicate names.
for (const [id, item] of Object.entries(payload.data).sort(([a], [b]) => Number(a) - Number(b))) {
  if (!item.name || !item.gold?.purchasable || !item.maps?.["11"] || Number(id) >= 100000 || item.requiredChampion || item.requiredAlly || item.inStore === false) continue;
  const tip = itemUsageTip(item.description, item.tags);
  if (tip && !tips.has(key(item.name))) tips.set(key(item.name), { name: item.name, tip });
}
const lines = [...tips.entries()].sort(([a], [b]) => a.localeCompare(b)).map(([name, entry]) => `  ${JSON.stringify(name)}: ${JSON.stringify(entry.tip)}, // ${entry.name.replace(/\*\//g, "")}`);
const text = `// Generated by scripts/build-item-tips.ts from Data Dragon ${version} item descriptions (rules: lib/item-synergy.ts).
// Data, not hand-written tips: regenerate after a patch instead of editing.
export const ITEM_TIPS: Readonly<Record<string, string>> = {
${lines.join("\n")}
};
`;
await writeFile(path.join(process.cwd(), "lib", "item-tips-data.ts"), text, "utf8");
console.log(`Wrote lib/item-tips-data.ts: ${tips.size} item tips from Data Dragon ${version}.`);
if (process.argv.includes("--print")) for (const entry of tips.values()) console.log(`${entry.name.padEnd(28)} ${entry.tip}`);
